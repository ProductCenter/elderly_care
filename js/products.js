/** 解析商品属性（兼容旧字段 serviceType） */
window.getProductAttrKey = function getProductAttrKey(productOrType) {
  if (!productOrType) return "instore";
  if (typeof productOrType === "string") {
    const t = productOrType;
    return t === "home" || t === "goods" || t === "instore" || t === "package" ? t : "instore";
  }
  const key = productOrType.productAttr || productOrType.serviceType || "instore";
  return key === "home" || key === "goods" || key === "instore" || key === "package" ? key : "instore";
};

window.getProductAttr = function getProductAttr(productOrType) {
  const key = window.getProductAttrKey(productOrType);
  return window.MALL_PRODUCT_ATTRS[key] || window.MALL_PRODUCT_ATTRS.instore;
};

/** 首页 Feed 分类：到店 / 到家 / 辅具租赁 / 邮寄到家（履约仍走实物发货） */
window.MALL_FEED_MAIL_CATS = [
  "goods_monitor",
  "goods_nutrition",
  "goods_consumable",
  "goods_safety",
];

window.getProductFeedKey = function getProductFeedKey(product) {
  if (!product) return "instore";
  const group = product.feedGroup;
  if (group === "mail" || group === "goods" || group === "home" || group === "instore") {
    return group;
  }
  const attr = window.getProductAttrKey(product);
  if (attr === "home") return "home";
  if (attr === "goods" || attr === "mail") {
    if (attr === "mail") return "mail";
    if (window.MALL_FEED_MAIL_CATS.includes(product.cat || "")) return "mail";
    return "goods";
  }
  return "instore";
};

