const PACKAGE_DRAFT_KEY = "kangyang_package_draft_v1";
const PACKAGE_GOODS_ID = "package_meal_month";

const ADMIN_STORE_MAP = {
  jinsheng: "store_cy001",
  chaoyang: "store_cy001",
  store_cy001: "store_cy001",
};

/** 读取后台「套餐权益」上架草稿 */
window.getPackageDraft = function getPackageDraft() {
  try {
    return JSON.parse(localStorage.getItem(PACKAGE_DRAFT_KEY) || "null");
  } catch {
    return null;
  }
};

/** 将后台上架草稿合并进商城可售套餐 SKU（演示连续用例） */
window.applyPackageDraftToMall = function applyPackageDraftToMall() {
  const draft = window.getPackageDraft();
  const base = window.MALL_PRODUCTS?.[PACKAGE_GOODS_ID];
  if (!draft || !base) return base || null;

  const storeId = ADMIN_STORE_MAP[draft.storeId] || draft.storeId || base.storeId || "store_cy001";
  const store = (window.MALL_STORES || {})[storeId] || window.MALL_STORES.store_cy001;
  const itemNames = (draft.items || []).map((it) => it.name).filter(Boolean);
  const features = itemNames.length
    ? itemNames.length <= 4
      ? itemNames
      : itemNames.slice(0, 3).concat([`等${itemNames.length}项`])
    : base.features;

  Object.assign(base, {
    name: draft.name || base.name,
    price: Number(draft.salePrice) || base.price,
    originPrice: Number(draft.guideTotalPrice) || base.originPrice,
    subtitle: draft.providerName
      ? `${draft.providerName} · ${draft.serviceDays || 26} 天套餐权益`
      : base.subtitle,
    desc: draft.intro || base.desc,
    features,
    badges: ["服务套餐", "套餐权益", `${draft.serviceDays || 26}天`],
    storeId,
    storeName: store?.storeName || base.storeName,
    storeAddress: store?.storeAddress || base.storeAddress,
    packageDraft: draft,
    tag: "",
    featured: false,
  });
  return base;
};

window.applyPackageDraftToMall();

/** 模拟拉取门店商品 SKU（带延迟，模拟接口） */
window.fetchStoreProductSku = function fetchStoreProductSku(goodsId, storeId) {
  return new Promise((resolve, reject) => {
    const delay = 280 + Math.floor(Math.random() * 220);
    setTimeout(() => {
      // 约 8% 概率模拟网络失败，便于验收异常提示
      if (Math.random() < 0) {
        reject(new Error("网络异常，门店数据加载失败"));
        return;
      }
      const store = (window.MALL_STORES || {})[storeId];
      const skuMap = (window.MALL_STORE_SKUS || {})[goodsId] || {};
      const sku = skuMap[storeId];
      if (!store || !sku) {
        reject(new Error("该门店暂未上架此商品"));
        return;
      }
      resolve({ store, sku });
    }, delay);
  });
};
